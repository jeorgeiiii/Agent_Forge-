"""Cluster 19 - byte storage backends (STORAGE_BACKEND = local | s3).

Both implement put / get / delete / exists, plus presigned URLs. The local
backend signs its own short-lived URLs (HMAC) served by this API; the S3 backend
uses real S3 presigned URLs, so large files go browser <-> bucket directly.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import time
from functools import lru_cache
from pathlib import Path
from typing import Iterator

from ..config import get_settings
from .common import ServiceError

CHUNK = 64 * 1024


class StorageBackend:
    name = "base"

    def put(self, key: str, data: bytes, mime: str) -> None: ...
    def get(self, key: str) -> Iterator[bytes]: ...
    def delete(self, key: str) -> None: ...
    def exists(self, key: str) -> bool: ...
    def size(self, key: str) -> int: ...
    def presigned_get(self, key: str, *, file_id: str, name: str, mime: str, ttl: int) -> str: ...
    def presigned_put(self, key: str, *, file_id: str, mime: str, ttl: int) -> str: ...


# --------------------------------------------------------------------------- local


def _signing_key() -> bytes:
    settings = get_settings()
    key = settings.file_signing_key or settings.internal_api_token
    if not key:
        raise ServiceError("Set FILE_SIGNING_KEY (or INTERNAL_API_TOKEN) to issue signed file links.", 503)
    return key.encode()


def sign_token(payload: dict) -> str:
    body = base64.urlsafe_b64encode(json.dumps(payload, separators=(",", ":")).encode()).decode().rstrip("=")
    mac = hmac.new(_signing_key(), body.encode(), hashlib.sha256).hexdigest()
    return f"{body}.{mac}"


def verify_token(token: str, op: str) -> dict:
    try:
        body, mac = token.rsplit(".", 1)
    except ValueError as error:
        raise ServiceError("Invalid link.", 403) from error
    expected = hmac.new(_signing_key(), body.encode(), hashlib.sha256).hexdigest()
    if not hmac.compare_digest(mac, expected):
        raise ServiceError("Invalid link.", 403)
    payload = json.loads(base64.urlsafe_b64decode(body + "=" * (-len(body) % 4)))
    if payload.get("op") != op:
        raise ServiceError("This link cannot be used for that.", 403)
    if payload.get("exp", 0) < time.time():
        raise ServiceError("This link has expired.", 410)
    return payload


class LocalStorage(StorageBackend):
    name = "local"

    def __init__(self, root: str):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if self.root not in path.parents:  # keys are generated by us, but never trust a path
            raise ServiceError("Invalid storage key.", 400)
        return path

    def put(self, key: str, data: bytes, mime: str) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".part")
        tmp.write_bytes(data)
        os.replace(tmp, path)  # atomic: readers never see half a file

    def get(self, key: str) -> Iterator[bytes]:
        path = self._path(key)
        if not path.exists():
            raise ServiceError("File content is missing from storage.", 404)
        with path.open("rb") as handle:
            while chunk := handle.read(CHUNK):
                yield chunk

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def exists(self, key: str) -> bool:
        return self._path(key).exists()

    def size(self, key: str) -> int:
        return self._path(key).stat().st_size

    def presigned_get(self, key: str, *, file_id: str, name: str, mime: str, ttl: int) -> str:
        token = sign_token({"op": "get", "file": file_id, "exp": int(time.time()) + ttl})
        return f"{get_settings().public_base_url.rstrip('/')}/files/signed/{token}"

    def presigned_put(self, key: str, *, file_id: str, mime: str, ttl: int) -> str:
        token = sign_token({"op": "put", "file": file_id, "exp": int(time.time()) + ttl})
        return f"{get_settings().public_base_url.rstrip('/')}/files/signed/{token}"


# ------------------------------------------------------------------------------ S3


class S3Storage(StorageBackend):
    """AWS S3 or any S3-compatible service (Cloudflare R2, MinIO, Backblaze B2, ...)."""

    name = "s3"

    def __init__(self):
        import boto3  # optional dependency: only needed when STORAGE_BACKEND=s3

        settings = get_settings()
        if not settings.s3_bucket:
            raise ServiceError("Set S3_BUCKET to use STORAGE_BACKEND=s3.", 503)
        self.bucket = settings.s3_bucket
        self.client = boto3.client(
            "s3",
            region_name=settings.s3_region or None,
            endpoint_url=settings.s3_endpoint_url or None,
            aws_access_key_id=settings.s3_access_key_id or None,
            aws_secret_access_key=settings.s3_secret_access_key or None,
        )

    def put(self, key: str, data: bytes, mime: str) -> None:
        self.client.put_object(Bucket=self.bucket, Key=key, Body=data, ContentType=mime)

    def get(self, key: str) -> Iterator[bytes]:
        from botocore.exceptions import ClientError

        try:
            body = self.client.get_object(Bucket=self.bucket, Key=key)["Body"]
        except ClientError as error:
            raise ServiceError("File content is missing from storage.", 404) from error
        yield from body.iter_chunks(CHUNK)

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=key)

    def exists(self, key: str) -> bool:
        from botocore.exceptions import ClientError

        try:
            self.client.head_object(Bucket=self.bucket, Key=key)
            return True
        except ClientError:
            return False

    def size(self, key: str) -> int:
        return int(self.client.head_object(Bucket=self.bucket, Key=key)["ContentLength"])

    def presigned_get(self, key: str, *, file_id: str, name: str, mime: str, ttl: int) -> str:
        return self.client.generate_presigned_url("get_object", ExpiresIn=ttl, Params={
            "Bucket": self.bucket, "Key": key, "ResponseContentType": mime,
            "ResponseContentDisposition": content_disposition(name, mime)})

    def presigned_put(self, key: str, *, file_id: str, mime: str, ttl: int) -> str:
        return self.client.generate_presigned_url("put_object", ExpiresIn=ttl,
                                                  Params={"Bucket": self.bucket, "Key": key, "ContentType": mime})


INLINE_TYPES = {"image/png", "image/jpeg", "image/gif", "image/webp", "application/pdf"}


def content_disposition(name: str, mime: str) -> str:
    """Only safe types render in the browser; everything else (HTML, SVG, ...) downloads."""
    kind = "inline" if mime in INLINE_TYPES else "attachment"
    ascii_name = name.encode("ascii", "replace").decode().replace('"', "'")
    from urllib.parse import quote

    return f"{kind}; filename=\"{ascii_name}\"; filename*=UTF-8''{quote(name)}"


@lru_cache
def get_storage() -> StorageBackend:
    settings = get_settings()
    if settings.storage_backend == "s3":
        return S3Storage()
    if settings.storage_backend != "local":
        raise ServiceError(f"Unknown STORAGE_BACKEND '{settings.storage_backend}'.", 500)
    return LocalStorage(settings.storage_local_dir)
