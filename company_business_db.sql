BEGIN;
DROP TABLE IF EXISTS support_tickets, invoices, shipments, order_items, orders, drivers, products, customers CASCADE;

CREATE TABLE customers (
  customer_id   int PRIMARY KEY,
  name          varchar NOT NULL,
  customer_type varchar NOT NULL CHECK (customer_type IN ('business','individual')),
  email         varchar NOT NULL,
  phone         varchar,
  city          varchar,
  region        varchar,
  gstin         varchar,
  created_at    timestamptz NOT NULL
);
CREATE TABLE products (
  product_id     int PRIMARY KEY,
  name           varchar NOT NULL,
  category       varchar NOT NULL,
  unit_price_inr numeric(10,2) NOT NULL,
  stock_qty      int,            -- NULL for services
  reorder_level  int
);
CREATE TABLE drivers (
  driver_id    int PRIMARY KEY,
  name         varchar NOT NULL,
  phone        varchar,
  base_city    varchar,
  vehicle_type varchar,
  vehicle_no   varchar,
  rating       numeric(2,1),
  is_active    boolean NOT NULL,
  joined_on    date
);
CREATE TABLE orders (
  order_id           varchar PRIMARY KEY,
  customer_id        int NOT NULL REFERENCES customers,
  order_date         timestamptz NOT NULL,
  origin_city        varchar,
  destination_city   varchar,
  destination_region varchar,
  status             varchar NOT NULL,  -- placed, picked_up, in_transit, delivered, delayed, delivered_late, cancelled, returned
  subtotal_inr       numeric(12,2),
  gst_inr            numeric(12,2),
  total_inr          numeric(12,2),
  promised_by        timestamptz,
  payment_method     varchar
);
CREATE TABLE order_items (
  item_id        int PRIMARY KEY,
  order_id       varchar NOT NULL REFERENCES orders,
  product_id     int NOT NULL REFERENCES products,
  quantity       int NOT NULL,
  unit_price_inr numeric(10,2),
  line_total_inr numeric(12,2)
);
CREATE TABLE shipments (
  shipment_id      int PRIMARY KEY,
  order_id         varchar NOT NULL REFERENCES orders,
  driver_id        int REFERENCES drivers,
  tracking_no      varchar UNIQUE,
  current_status   varchar,
  current_location varchar,
  eta              timestamptz,
  delivered_at     timestamptz,
  delay_reason     varchar,
  damaged          boolean DEFAULT false
);
CREATE TABLE invoices (
  invoice_id  varchar PRIMARY KEY,
  order_id    varchar NOT NULL REFERENCES orders,
  customer_id int NOT NULL REFERENCES customers,
  issued_on   date,
  due_on      date,
  amount_inr  numeric(12,2),
  status      varchar  -- paid, unpaid, overdue, void
);
CREATE TABLE support_tickets (
  ticket_id   varchar PRIMARY KEY,
  customer_id int REFERENCES customers,
  order_id    varchar REFERENCES orders,
  category    varchar,
  priority    varchar,
  subject     varchar,
  body        text,
  status      varchar,
  assigned_to varchar,
  created_at  timestamptz,
  resolved_at timestamptz,
  csat        int
);

